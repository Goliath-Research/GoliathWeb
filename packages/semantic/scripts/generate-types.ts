import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { ActionsCatalog, SemanticCatalog } from "../src/catalog-types.ts";
import { interfaceFromRowSchema, unionFromLiterals } from "./json-schema-to-ts.ts";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const generatedDir = join(packageRoot, "generated");

function readCache<T>(name: string): T {
  const text = readFileSync(join(packageRoot, "cache", name), "utf8");
  return JSON.parse(text) as T;
}

function writeGenerated(fileName: string, contents: string): void {
  const banner = "// Generated by packages/semantic/scripts/generate-types.ts — do not edit.\n";
  writeFileSync(join(generatedDir, fileName), banner + contents, "utf8");
}

function main(): void {
  const semantic = readCache<SemanticCatalog>("goliathapp-semantic.json");
  const organization = semantic.entities["core.organization"];
  if (!organization?.row_schema.title) {
    throw new Error("core.organization row_schema is missing a title");
  }
  writeGenerated(
    "organization-row.ts",
    interfaceFromRowSchema(organization.row_schema.title, organization.row_schema),
  );

  const appActions = readCache<ActionsCatalog>("goliathapp-actions.json");
  writeGenerated(
    "goliathapp-action-codes.ts",
    unionFromLiterals("GoliathAppActionCode", Object.keys(appActions.actions).sort()),
  );

  const omicsActions = readCache<ActionsCatalog>("goliathomics-actions.json");
  writeGenerated(
    "omics-action-codes.ts",
    unionFromLiterals("GoliathOmicsActionCode", Object.keys(omicsActions.actions).sort()),
  );

  const manifest = {
    organizationContentHash: organization.content_hash,
    goliathappActionCount: Object.keys(appActions.actions).length,
    goliathomicsActionCount: Object.keys(omicsActions.actions).length,
  };
  writeGenerated("manifest.ts", `export const GENERATED_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n`);
}

main();
